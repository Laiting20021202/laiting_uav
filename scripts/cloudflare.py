#!/usr/bin/env python3
"""Install cloudflared, authorize a zone, and configure named HTTP + SSH ingress."""
import argparse
import hashlib
import json
import os
import platform
import subprocess
import urllib.request
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BINARY = Path.home()/".local/bin/cloudflared"
TUNNEL_NAME = "laiting-uav-v2"


def run(*args, capture=False):
    return subprocess.run([str(BINARY), *args], check=True, text=True, capture_output=capture)


def install():
    arch = {"aarch64": "arm64", "x86_64": "amd64"}.get(platform.machine())
    if not arch:
        raise SystemExit("Unsupported architecture")
    request = urllib.request.Request("https://api.github.com/repos/cloudflare/cloudflared/releases/latest", headers={"User-Agent": "laiting-uav-installer", "Accept": "application/vnd.github+json"})
    with urllib.request.urlopen(request, timeout=30) as response:
        release = json.load(response)
    asset = next(a for a in release["assets"] if a["name"] == f"cloudflared-linux-{arch}")
    expected = asset.get("digest", "")
    if not expected.startswith("sha256:"):
        raise SystemExit("Release missing SHA256 digest; no installation performed")
    BINARY.parent.mkdir(parents=True, exist_ok=True)
    temp = BINARY.with_suffix(".download")
    digest = hashlib.sha256()
    try:
        with urllib.request.urlopen(asset["browser_download_url"], timeout=60) as response, temp.open("wb") as output:
            while True:
                block = response.read(1024*1024)
                if not block:
                    break
                digest.update(block)
                output.write(block)
        if digest.hexdigest() != expected.split(":", 1)[1]:
            raise SystemExit("SHA256 verification failed")
        temp.chmod(0o755)
        os.replace(temp, BINARY)
    finally:
        temp.unlink(missing_ok=True)
    run("--version")


def setup():
    if not (Path.home()/".cloudflared/cert.pem").exists():
        raise SystemExit("Authorize first: .venv/bin/python scripts/cloudflare.py login")
    existing = json.loads(run("tunnel", "list", "--output", "json", capture=True).stdout)
    # CLI excludes deleted tunnels by default; Go encodes an unset time as year 0001.
    matches = [t for t in existing if t["name"] == TUNNEL_NAME]
    if not matches:
        run("tunnel", "create", TUNNEL_NAME)
        existing = json.loads(run("tunnel", "list", "--output", "json", capture=True).stdout)
        matches = [t for t in existing if t["name"] == TUNNEL_NAME]
    if len(matches) != 1:
        raise SystemExit("Cannot identify a unique active UAV tunnel; retry after Cloudflare finishes creating it")
    tunnel_id = str(uuid.UUID(matches[0]["id"]))
    credentials = Path.home()/".cloudflared"/(tunnel_id+".json")
    if not credentials.exists():
        raise SystemExit("Named tunnel exists but local credential file is missing; restore it before setup")
    credentials.chmod(0o600)
    text = f"""# Generated by scripts/cloudflare.py; secrets remain outside the project.
tunnel: {tunnel_id}
credentials-file: {credentials}
protocol: http2
metrics: 127.0.0.1:20241
ingress:
  - hostname: uav.laiting1202.com
    service: http://127.0.0.1:8080
    originRequest:
      connectTimeout: 10s
      disableChunkedEncoding: false
  - hostname: ssh-uav.laiting1202.com
    service: ssh://127.0.0.1:22
  - service: http_status:404
"""
    path = ROOT/"config/cloudflared.yml"
    # Exclusive replacement through a private temporary file.
    temp = path.with_suffix(".tmp")
    fd = os.open(temp, os.O_CREAT | os.O_TRUNC | os.O_WRONLY, 0o600)
    with os.fdopen(fd, "w") as output:
        output.write(text)
    os.replace(temp, path)
    path.chmod(0o600)
    run("tunnel", "--config", str(path), "ingress", "validate")
    # No --overwrite-dns: existing records must not be replaced silently.
    for hostname in ("uav.laiting1202.com", "ssh-uav.laiting1202.com"):
        run("tunnel", "route", "dns", tunnel_id, hostname)
    print("DNS and ingress configured. Enable services: .venv/bin/python scripts/services.py --tunnel")
    print("For SSH, add a Cloudflare Access application and allow only your chosen identity; see docs/DEPLOYMENT.md.")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("action", choices=["install", "login", "setup"])
    args = p.parse_args()
    if args.action == "install":
        install()
    elif args.action == "login":
        run("tunnel", "login")
    else:
        setup()


if __name__ == "__main__":
    main()
